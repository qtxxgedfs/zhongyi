function p.skchar2(code)
    local code1=code.args[1] or '1'
    local alttext=nil
    if not (nil == code.args[2] or '{{{2}}}' == code.args[2]) then
        -- replace sensitive chars to prevent XSS
        alttext=string.gsub(code.args[2], ">", "&gt;")
        alttext=string.gsub(alttext, "<", "&lt;")
        alttext=string.gsub(alttext, "[|{}]", "")
    end
    local charpair = skchars2[code1]
    if (nil == charpair) then
       charpair = {"", ""}
    end
    local char = charpair[1] or ""
    if char == "" then
        alttext = (alttext or charpair[2] or "SKchar2")
        char = ("[[File:SKQSfont2.pdf|page=" .. code1 .."|20px|link=|alt=" .. alttext .. "]]")
    end
    return char
end
